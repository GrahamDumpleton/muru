"""gRPC service mounts (design specification section 6.13).

A gRPC mount's entrypoint is a registration function. It is called with a
`Server`, which takes what code generated by grpcio-tools adds to a grpcio
server, and the worker then serves the registered methods. The edge
unframes, decompresses and times each call and hands the worker whole
messages on a ``grpc`` scope, which `Dispatcher` runs: synchronous
handlers on the mount's threads, asynchronous ones on the worker's event
loop. grpcio provides the status codes and the generated code's imports;
its own server never runs in a worker.
"""

from __future__ import annotations

import asyncio
import base64
import inspect
import sys
import time
import traceback
from collections.abc import (
    AsyncIterator,
    Awaitable,
    Callable,
    Coroutine,
    Iterable,
    Iterator,
    MutableMapping,
)
from concurrent.futures import ThreadPoolExecutor
from typing import Any, NamedTuple, NoReturn, TypeVar

try:
    import grpc
except ImportError as error:  # pragma: no cover - depends on the interpreter
    raise ImportError(
        "gRPC mounts need grpcio, which this Python cannot import (section 6.13)"
    ) from error

__all__ = ["Dispatcher", "Server", "enable_reflection"]

T = TypeVar("T")

Metadata = tuple[tuple[str, str | bytes], ...]

# Request headers that belong to the protocol rather than the call's
# metadata.

PROTOCOL_HEADERS = frozenset({"content-type", "content-length", "te", "host"})

# How many request messages are read ahead of the handler.

READ_AHEAD = 8

STATUS_BY_VALUE = {code.value[0]: code for code in grpc.StatusCode}


class HandlerCallDetails(NamedTuple):
    """What a generic handler is asked to find a method handler for."""

    method: str
    invocation_metadata: Metadata


class Server:
    """What a gRPC mount's registration function is given.

    It takes the registrations that code from grpcio-tools makes on a
    grpcio server, ``add_generic_rpc_handlers`` and
    ``add_registered_method_handlers``, and keeps each method's handler.
    """

    def __init__(self) -> None:
        self.methods: dict[str, Any] = {}
        self.generic: list[Any] = []
        self.services: list[str] = []

    def add_generic_rpc_handlers(self, generic_rpc_handlers: Iterable[Any]) -> None:
        """Add handlers that find a method's handler by its name."""

        for handler in generic_rpc_handlers:
            self.generic.append(handler)
            service_name = getattr(handler, "service_name", None)

            if callable(service_name):
                self._add_service(service_name())

    def add_registered_method_handlers(
        self, service_name: str, method_handlers: dict[str, Any]
    ) -> None:
        """Add a service's handlers by method name."""

        self._add_service(service_name)

        for method, handler in method_handlers.items():
            self.methods[f"/{service_name}/{method}"] = handler

    def _add_service(self, name: str) -> None:
        if name not in self.services:
            self.services.append(name)

    def handler(self, path: str, metadata: Metadata) -> Any | None:
        """Return the handler of the method at `path`, or None when none is registered."""

        handler = self.methods.get(path)

        if handler is not None:
            return handler

        details = HandlerCallDetails(path, metadata)

        for generic in self.generic:
            handler = generic.service(details)

            if handler is not None:
                return handler

        return None

    def listing(self, mount: str) -> list[tuple[str, str, bool, bool]]:
        """Describe the registered methods for the edge.

        Each is its path, the mount, and whether its requests and its
        responses stream. A generic handler whose methods cannot be listed
        stands for its whole service, as a path ending in ``/``.
        """

        found: dict[str, tuple[str, str, bool, bool]] = {}

        def add(path: str, handler: Any) -> None:
            streams = (bool(handler.request_streaming), bool(handler.response_streaming))
            found.setdefault(path, (path, mount, *streams))

        for path, handler in self.methods.items():
            add(path, handler)

        for generic in self.generic:
            listed = getattr(generic, "_method_handlers", None)

            if isinstance(listed, dict):
                for path, handler in listed.items():
                    add(path, handler)

                continue

            service_name = getattr(generic, "service_name", None)

            if callable(service_name):
                prefix = f"/{service_name()}/"
                found.setdefault(prefix, (prefix, mount, True, True))

        return list(found.values())


def register(entrypoint: Callable[[Server], Any]) -> Server:
    """Call a mount's registration function with a new server and return it."""

    server = Server()
    entrypoint(server)

    if not server.methods and not server.generic:
        raise RuntimeError("the registration function added no gRPC services")

    return server


def enable_reflection(servers: list[Server]) -> None:
    """Serve server reflection for every service the servers registered, from the first."""

    try:
        from grpc_reflection.v1alpha import reflection
    except ImportError as error:
        raise RuntimeError(
            "reflection = true needs grpcio-reflection, which this Python cannot import"
        ) from error

    names = [name for server in servers for name in server.services]
    names.append(reflection.SERVICE_NAME)
    reflection.enable_server_reflection(names, servers[0])


class Dispatcher:
    """Run the calls of one gRPC mount.

    The worker's runner calls it with each request's scope, ``receive``
    and ``send``, as it would an ASGI application. A plain HTTP request is
    answered 404.
    """

    def __init__(self, server: Server, threads: int) -> None:
        self.server = server
        self.executor = ThreadPoolExecutor(
            max_workers=max(1, threads), thread_name_prefix="muru-grpc"
        )

    async def __call__(self, scope: MutableMapping[str, Any], receive: Any, send: Any) -> None:
        if scope["type"] != "grpc":
            await send(
                {
                    "type": "http.response.start",
                    "status": 404,
                    "headers": [(b"content-type", b"text/plain; charset=utf-8")],
                }
            )
            await send({"type": "http.response.body", "body": b"This serves gRPC calls only.\n"})
            return

        await Call(scope, receive, send).run(self.server, self.executor)


class Aborted(Exception):
    """Raised by ``context.abort()`` to end the call with the status it set."""


class Call:
    """One gRPC call: its request messages, its status and its output."""

    def __init__(
        self,
        scope: MutableMapping[str, Any],
        receive: Callable[[], Awaitable[dict[str, Any]]],
        send: Callable[[dict[str, Any]], Awaitable[None]],
    ) -> None:
        self.loop = asyncio.get_running_loop()
        self.path: str = scope["path"]
        self.metadata = decode_metadata(scope["headers"])
        extensions = scope.get("extensions") or {}
        self.deadline: float | None = (extensions.get("muru") or {}).get("deadline")
        self.peer = describe_peer(scope.get("client"))
        self.receive = receive
        self.send = send
        self.requests: asyncio.Queue[bytes | None] = asyncio.Queue()
        self.room = asyncio.Semaphore(READ_AHEAD)
        self.request_over = False
        self.code: grpc.StatusCode | None = None
        self.details = ""
        self.trailing: Metadata = ()
        self.started = False
        self.finished = False
        self.cancelled = False
        self.callbacks: list[Callable[[], None]] = []
        self.handler_task: asyncio.Future[Any] | None = None

    async def run(self, server: Server, executor: ThreadPoolExecutor) -> None:
        """Find the method's handler, run it, and end the call with its status."""

        handler = server.handler(self.path, self.metadata)

        if handler is None:
            await self.finish(grpc.StatusCode.UNIMPLEMENTED, f"Method not found: {self.path}")
            return

        behaviour = method_behaviour(handler)
        pump = asyncio.ensure_future(self.pump())

        try:
            if inspect.iscoroutinefunction(behaviour) or inspect.isasyncgenfunction(behaviour):
                self.handler_task = asyncio.ensure_future(self.invoke(handler, behaviour))

                try:
                    await self.handler_task
                except asyncio.CancelledError:
                    # The client went away, which cancels the handler; a
                    # cancellation from outside, the soft timeout's, goes on.

                    if not self.cancelled:
                        raise
            else:
                await self.loop.run_in_executor(executor, self.invoke_sync, handler, behaviour)

            await self.finish(*self.outcome())
        finally:
            pump.cancel()

    def outcome(self) -> tuple[grpc.StatusCode, str]:
        """Return the status the call ends with."""

        if self.cancelled:
            return grpc.StatusCode.CANCELLED, "the client cancelled the call"

        return self.code or grpc.StatusCode.OK, self.details

    def failed(self, error: BaseException) -> None:
        """Record an exception from the handler, as grpcio does."""

        if isinstance(error, Aborted):
            return

        detail = "".join(traceback.format_exception(error))
        sys.stderr.write(f"muru: the gRPC handler for {self.path} raised:\n{detail}")
        sys.stderr.flush()

        if self.code is None or self.code is grpc.StatusCode.OK:
            self.code = grpc.StatusCode.UNKNOWN
            self.details = f"Exception calling application: {error}"

    # The request side: the pump reads ahead of the handler, so the end
    # of the call is noticed while the handler runs.

    async def pump(self) -> None:
        """Move the request's messages into the queue and notice when the call is over."""

        while True:
            await self.room.acquire()
            event = await self.receive()
            kind = event.get("type")

            if kind == "grpc.message":
                self.requests.put_nowait(event["message"])
                continue

            self.room.release()

            if kind == "grpc.end":
                self.requests.put_nowait(None)
                continue

            # grpc.disconnect: the call is over, ended by the client if the
            # handler has not finished it.

            self.requests.put_nowait(None)

            if not self.finished:
                self.cancel()

            return

    def cancel(self) -> None:
        """End the call for the client's sake: the handler is told and its callbacks run."""

        if self.cancelled or self.finished:
            return

        self.cancelled = True

        if self.handler_task is not None:
            self.handler_task.cancel()

        self.run_callbacks()

    async def next_message(self) -> bytes | None:
        """Return the next request message, or None once there are no more."""

        if self.request_over:
            return None

        data = await self.requests.get()

        if data is None:
            self.request_over = True
            return None

        self.room.release()
        return data

    def deserialize(self, handler: Any, data: bytes) -> Any:
        """Decode a request message with the handler's deserializer."""

        deserializer = handler.request_deserializer

        if deserializer is None:
            return data

        try:
            return deserializer(data)
        except Exception:
            self.code = grpc.StatusCode.INTERNAL
            self.details = "Exception deserializing request!"
            raise

    async def unary_request(self, handler: Any) -> Any:
        """Return the one request message of a call whose requests do not stream."""

        data = await self.next_message()

        if data is None:
            self.code = grpc.StatusCode.INTERNAL
            self.details = "the call ended without its request message"
            raise Aborted(self.details)

        return self.deserialize(handler, data)

    async def request_stream(self, handler: Any) -> AsyncIterator[Any]:
        """Yield the request messages, for an asynchronous handler."""

        while (data := await self.next_message()) is not None:
            yield self.deserialize(handler, data)

    # The response side.

    async def start(self, metadata: Iterable[tuple[str, str | bytes]] | None) -> None:
        """Send the initial metadata, before any response message."""

        if self.started:
            raise ValueError("the initial metadata has already been sent")

        self.started = True
        await self.send({"type": "grpc.start", "headers": encode_metadata(metadata or ())})

    async def write(self, handler: Any, response: Any) -> None:
        """Send one response message."""

        if self.finished or self.cancelled:
            return

        serializer = handler.response_serializer
        data = serializer(response) if serializer is not None else response
        self.started = True
        await self.send({"type": "grpc.message", "message": bytes(data)})

    async def respond(self, handler: Any, response: Any) -> None:
        """Send the one response of a call whose responses do not stream."""

        if self.code not in (None, grpc.StatusCode.OK):
            return

        if response is None:
            self.code = grpc.StatusCode.INTERNAL
            self.details = "the handler returned no response"
            return

        await self.write(handler, response)

    async def finish(self, code: grpc.StatusCode, details: str) -> None:
        """End the call with its status, details and trailing metadata."""

        if self.finished:
            return

        self.finished = True
        trailers = [(b"grpc-status", str(code.value[0]).encode())]

        if details:
            trailers.append((b"grpc-message", percent_encode(details)))

        trailers.extend(encode_metadata(self.trailing))
        await self.send({"type": "grpc.finish", "trailers": trailers})
        self.run_callbacks()

    def run_callbacks(self) -> None:
        """Run the callbacks added for the end of the call, once."""

        callbacks, self.callbacks = self.callbacks, []

        for callback in callbacks:
            try:
                callback()
            except Exception:
                traceback.print_exc()

    # Running the handler.

    async def invoke(self, handler: Any, behaviour: Callable[..., Any]) -> None:
        """Run an asynchronous handler on the loop."""

        context = AioServicerContext(self, handler)

        try:
            if handler.request_streaming:
                request: Any = self.request_stream(handler)
            else:
                request = await self.unary_request(handler)

            result = behaviour(request, context)

            if not handler.response_streaming:
                await self.respond(handler, await result)
            elif inspect.isasyncgen(result):
                async for response in result:
                    await self.write(handler, response)
            else:
                # A coroutine that writes with context.write().

                await result
        except Exception as error:
            self.failed(error)

    def invoke_sync(self, handler: Any, behaviour: Callable[..., Any]) -> None:
        """Run a synchronous handler, on one of the mount's threads."""

        context = ServicerContext(self, handler)

        try:
            if handler.request_streaming:
                request: Any = self.sync_requests(handler)
            else:
                request = self.wait(self.unary_request(handler))

            result = behaviour(request, context)

            if not handler.response_streaming:
                self.wait(self.respond(handler, result))
                return

            for response in result:
                if self.cancelled:
                    break

                self.wait(self.write(handler, response))
        except Exception as error:
            self.failed(error)

    def sync_requests(self, handler: Any) -> Iterator[Any]:
        """Yield the request messages, for a synchronous handler."""

        while (data := self.wait(self.next_message())) is not None:
            yield self.deserialize(handler, data)

    def wait(self, coroutine: Coroutine[Any, Any, T]) -> T:
        """Run a coroutine on the loop from a handler's thread and return its result."""

        return asyncio.run_coroutine_threadsafe(coroutine, self.loop).result()

    def abort(self, code: Any, details: str) -> NoReturn:
        """End the call with a status other than OK, raising to leave the handler."""

        if status(code) is grpc.StatusCode.OK:
            raise ValueError("abort() needs a status other than OK")

        self.code = status(code)
        self.details = details
        raise Aborted(details)

    def time_remaining(self) -> float | None:
        """Return the seconds until the call's deadline, or None when it has none."""

        if self.deadline is None:
            return None

        return max(0.0, self.deadline - time.time())


class Context:
    """What the two kinds of ``context`` share: the commonly used parts of grpc.ServicerContext."""

    def __init__(self, call: Call, handler: Any) -> None:
        self._call = call
        self._handler = handler

    def invocation_metadata(self) -> Metadata:
        """Return the metadata the client sent."""

        return self._call.metadata

    def peer(self) -> str:
        """Return the client as the edge resolved it, for example ipv4:192.0.2.7:51234."""

        return self._call.peer

    def peer_identities(self) -> None:
        """No client certificates are passed on: None."""

        return None

    def peer_identity_key(self) -> None:
        """No client certificates are passed on: None."""

        return None

    def auth_context(self) -> dict[str, list[bytes]]:
        """No authentication context is passed on: empty."""

        return {}

    def time_remaining(self) -> float | None:
        """Seconds until the deadline, or None when the call has none."""

        return self._call.time_remaining()

    def is_active(self) -> bool:
        """Whether the call is still going: not finished and not cancelled."""

        return not (self._call.finished or self._call.cancelled)

    def cancel(self) -> None:
        """End the call as cancelled."""

        self._call.cancel()

    def add_callback(self, callback: Callable[[], None]) -> bool:
        """Call `callback` when the call ends; False when it already has."""

        if self._call.finished or self._call.cancelled:
            return False

        self._call.callbacks.append(callback)
        return True

    def set_trailing_metadata(self, trailing_metadata: Iterable[tuple[str, str | bytes]]) -> None:
        """Set the metadata sent with the status."""

        self._call.trailing = tuple(trailing_metadata)

    def trailing_metadata(self) -> Metadata:
        """Return the trailing metadata set so far."""

        return self._call.trailing

    def set_code(self, code: grpc.StatusCode) -> None:
        """Set the status the call ends with."""

        self._call.code = status(code)

    def set_details(self, details: str) -> None:
        """Set the status's details."""

        self._call.details = details

    def code(self) -> grpc.StatusCode | None:
        """Return the status set so far."""

        return self._call.code

    def details(self) -> str:
        """Return the details set so far."""

        return self._call.details

    def set_compression(self, compression: Any) -> None:
        """Ignore the request: the edge sends responses uncompressed."""

    def disable_next_message_compression(self) -> None:
        """Ignore the request: the edge sends responses uncompressed."""


class ServicerContext(Context):
    """The ``context`` of a synchronous handler, as grpc.ServicerContext has it."""

    def send_initial_metadata(self, initial_metadata: Iterable[tuple[str, str | bytes]]) -> None:
        """Send the initial metadata now, before any response."""

        self._call.wait(self._call.start(initial_metadata))

    def abort(self, code: grpc.StatusCode, details: str) -> NoReturn:
        """End the call with a status other than OK, raising to leave the handler."""

        self._call.abort(code, details)

    def abort_with_status(self, status: Any) -> NoReturn:
        """End the call with a grpc.Status, its trailing metadata included."""

        self._call.trailing = tuple(status.trailing_metadata or ())
        self._call.abort(status.code, status.details)


class AioServicerContext(Context):
    """The ``context`` of an asynchronous handler, as grpc.aio.ServicerContext has it."""

    async def send_initial_metadata(
        self, initial_metadata: Iterable[tuple[str, str | bytes]]
    ) -> None:
        """Send the initial metadata now, before any response."""

        await self._call.start(initial_metadata)

    async def abort(
        self, code: grpc.StatusCode, details: str = "", trailing_metadata: Any = ()
    ) -> NoReturn:
        """End the call with a status other than OK, raising to leave the handler."""

        if trailing_metadata:
            self._call.trailing = tuple(trailing_metadata)

        self._call.abort(code, details)

    async def abort_with_status(self, status: Any) -> NoReturn:
        """End the call with a grpc.Status, its trailing metadata included."""

        self._call.trailing = tuple(status.trailing_metadata or ())
        self._call.abort(status.code, status.details)

    async def write(self, message: Any) -> None:
        """Send one response message."""

        await self._call.write(self._handler, message)

    async def read(self) -> Any:
        """Return the next request message, or grpc.aio.EOF after the last."""

        data = await self._call.next_message()

        if data is None:
            return grpc.aio.EOF

        return self._call.deserialize(self._handler, data)

    def cancelled(self) -> bool:
        """Whether the client cancelled the call."""

        return self._call.cancelled

    def done(self) -> bool:
        """Whether the call has ended."""

        return self._call.finished or self._call.cancelled

    def add_done_callback(self, callback: Callable[[AioServicerContext], None]) -> None:
        """Call `callback` with this context when the call ends."""

        self._call.callbacks.append(lambda: callback(self))


def method_behaviour(handler: Any) -> Callable[..., Any]:
    """Return the function that implements a method handler's kind of call."""

    if handler.request_streaming and handler.response_streaming:
        behaviour = handler.stream_stream
    elif handler.request_streaming:
        behaviour = handler.stream_unary
    elif handler.response_streaming:
        behaviour = handler.unary_stream
    else:
        behaviour = handler.unary_unary

    if behaviour is None:
        raise RuntimeError("the method handler has no function for its kind of call")

    return behaviour  # type: ignore[no-any-return]


def status(code: Any) -> grpc.StatusCode:
    """Return a grpc.StatusCode, from itself or its number."""

    if isinstance(code, grpc.StatusCode):
        return code

    return STATUS_BY_VALUE[int(code)]


def decode_metadata(headers: Iterable[tuple[bytes, bytes]]) -> Metadata:
    """Return the call's metadata from its request headers, binary values decoded."""

    metadata: list[tuple[str, str | bytes]] = []

    for raw_name, raw_value in headers:
        name = raw_name.decode("latin-1")

        if name in PROTOCOL_HEADERS or name.startswith("grpc-"):
            continue

        if name.endswith("-bin"):
            padded = raw_value + b"=" * (-len(raw_value) % 4)
            metadata.append((name, base64.b64decode(padded)))
        else:
            metadata.append((name, raw_value.decode("utf-8", "replace")))

    return tuple(metadata)


def encode_metadata(metadata: Iterable[tuple[str, str | bytes]]) -> list[tuple[bytes, bytes]]:
    """Metadata as header pairs: names lower case, binary values base64 encoded."""

    headers: list[tuple[bytes, bytes]] = []

    for name, value in metadata:
        key = name.lower()
        data = value.encode() if isinstance(value, str) else bytes(value)

        if key.endswith("-bin"):
            data = base64.b64encode(data).rstrip(b"=")

        headers.append((key.encode("ascii"), data))

    return headers


def percent_encode(text: str) -> bytes:
    """Encode grpc-message: UTF-8, with bytes outside printable ASCII and % escaped."""

    out = bytearray()

    for byte in text.encode():
        if 0x20 <= byte <= 0x7E and byte != 0x25:
            out.append(byte)
        else:
            out.extend(f"%{byte:02X}".encode())

    return bytes(out)


def describe_peer(client: tuple[str, int] | None) -> str:
    """Name a peer as grpcio does: ipv4:ADDRESS:PORT or ipv6:[ADDRESS]:PORT."""

    if client is None:
        return "unknown"

    address, port = client

    if ":" in address:
        return f"ipv6:[{address}]:{port}"

    return f"ipv4:{address}:{port}"
